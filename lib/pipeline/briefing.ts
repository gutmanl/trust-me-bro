import { getCurrentActor } from "../identity";
import type { BriefingImport, BriefingViewModel } from "../register";
import { buildBriefingViewModel } from "../register";
import {
  BriefingAlreadyImportedError,
  InvalidBriefingInputError,
} from "./errors";
import { requireProjectStore } from "./projects";
import { briefingRenderContext } from "./research/independence";
import { RESEARCH_TOOL_PREFIX } from "./research/provenance";
import { desugarBriefingCitations } from "./sources/reference-scan/desugar-citations";
import type { CitationRewriteReport } from "./sources/reference-scan/desugar-citations";

export interface ImportBriefingInput {
  projectId: string;
  /** The briefing as generated by the upstream deep-research tool
   * (Markdown or plain text). */
  content: string;
  /** Name of the generating tool, recorded in briefing_import.tool. */
  tool: string;
  /** OPTIONAL companion BibTeX file (BibTeX support), for a briefing that
   * cites Pandoc-style — a thesis chapter, typically. Its citations are
   * desugared into the Markdown footnote convention BEFORE the briefing is
   * frozen; the `.bib` itself is deliberately NOT persisted, so the frozen
   * briefing stays self-contained and no register schema moves. */
  bibliography?: string;
}

/**
 * The frozen briefing, plus — when a bibliography came with it — the German
 * report of the citation rewrite.
 *
 * Structurally a `BriefingImport`, so every existing caller is unaffected.
 * `citationRewrite` is camelCase precisely BECAUSE it is not a register
 * field: the snake_case convention in this codebase marks what the persisted
 * schema owns, and this report is import-time knowledge that is never
 * written anywhere.
 */
export interface BriefingImportOutcome extends BriefingImport {
  readonly citationRewrite?: CitationRewriteReport;
}

/**
 * Freezes the original briefing (TMB-22): stores the exact input as an
 * immutable blob, records project.briefing_import with checksum, time and
 * generating tool, and appends the briefing_imported chain event. The check
 * runs inside the transaction, so a concurrent import cannot slip past it.
 * Afterwards briefing.md is rendered as a first (claim-free) projection.
 *
 * The single route by which briefing truth enters the register: both the
 * user-facing import (importBriefing) and in-application research
 * (run-research) freeze through here, so there is no second write path to
 * keep consistent. Internal on purpose — importBriefing is the public
 * use-case, and it guards the provenance prefix that this primitive trusts.
 */
export async function freezeBriefing(
  input: ImportBriefingInput,
): Promise<BriefingImport> {
  if (input.content.trim().length === 0) {
    throw new InvalidBriefingInputError("Das Briefing darf nicht leer sein.");
  }
  const tool = input.tool.trim();
  if (tool.length === 0) {
    throw new InvalidBriefingInputError(
      "Bitte das erzeugende Werkzeug angeben (z. B. den Namen des Deep-Research-Tools).",
    );
  }
  const store = requireProjectStore(input.projectId);
  await store.transaction((tx) => {
    if (tx.getProject().briefing_import) {
      throw new BriefingAlreadyImportedError(input.projectId);
    }
    const blob = store.blobs().put(input.content, "md");
    tx.recordBriefingImport({
      sha256: blob.sha256,
      blob_path: blob.blobPath,
      tool,
      actor: getCurrentActor(),
    });
  });
  const register = await store.read();
  await store.renderBriefingFile(briefingRenderContext(register));
  return register.project.briefing_import as BriefingImport;
}

/**
 * Imports a briefing produced by an external tool (the public use-case the
 * web layer calls). Identical to freezeBriefing but reserves the
 * `trustmebro-research/` provenance prefix: it marks a briefing this
 * application researched itself, and the independence notice keys on it, so
 * a user-supplied tool name must not be able to forge it. The research
 * pipeline writes that prefix through freezeBriefing directly.
 *
 * It is also where a companion `.bib` is consumed (BibTeX support). The
 * rewrite happens HERE rather than in freezeBriefing because it is a
 * property of importing someone else's text, not of freezing: what gets
 * frozen — and hashed, and shown as "die Originalfassung" — is the rewritten,
 * self-contained briefing. Nothing downstream ever sees the `.bib`.
 *
 * This closes the local-forgery path only. A briefing inside an imported
 * .tmb bundle can still name any tool it likes — the register binds no chain
 * to a specific installation, so that provenance claim is not authentic:
 * an accepted, pre-existing property of the bundle trust model, not
 * something this guard can or claims to close.
 */
export async function importBriefing(
  input: ImportBriefingInput,
): Promise<BriefingImportOutcome> {
  if (input.tool.trim().startsWith(RESEARCH_TOOL_PREFIX)) {
    throw new InvalidBriefingInputError(
      `Der Präfix „${RESEARCH_TOOL_PREFIX}" ist für in der Anwendung ` +
        "erzeugte Briefings reserviert und kann nicht als Werkzeugname " +
        "angegeben werden.",
    );
  }
  const rewrite =
    input.bibliography && input.bibliography.trim().length > 0
      ? desugarBriefingCitations(input.content, input.bibliography)
      : null;
  const briefing = await freezeBriefing(
    rewrite === null ? input : { ...input, content: rewrite.text },
  );
  return rewrite === null
    ? briefing
    : { ...briefing, citationRewrite: rewrite.report };
}

/**
 * Structured briefing view model for the review workspace (TMB-33), built
 * from the frozen original and the current register via the shared
 * projection; null before a briefing was imported.
 */
export async function getBriefingViewModel(
  projectId: string,
): Promise<BriefingViewModel | null> {
  const store = requireProjectStore(projectId);
  const register = await store.read();
  const meta = register.project.briefing_import;
  if (!meta) {
    return null;
  }
  return buildBriefingViewModel(
    store.blobs().readText(meta.blob_path),
    register,
  );
}

/** The frozen briefing with its import metadata, or null before import. */
export async function getBriefing(
  projectId: string,
): Promise<{ meta: BriefingImport; text: string } | null> {
  const store = requireProjectStore(projectId);
  const register = await store.read();
  const meta = register.project.briefing_import;
  if (!meta) {
    return null;
  }
  return { meta, text: store.blobs().readText(meta.blob_path) };
}
